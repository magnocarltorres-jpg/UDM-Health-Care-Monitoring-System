CREATE OR REPLACE FUNCTION public.record_medicine_dispense_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.inventory_movements (
    medicine_id, movement_type, quantity_change, dispensation_id,
    patient_id, assessment_id, recorded_by, reason
  )
  VALUES (
    NEW.medicine_id, 'dispensed', -NEW.quantity, NEW.id, NEW.patient_id,
    NEW.assessment_id, NEW.dispensed_by, 'Dispensed during clinic assessment'
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS medicine_dispensation_inventory_movement
  ON public.medicine_dispensations;
CREATE TRIGGER medicine_dispensation_inventory_movement
  AFTER INSERT ON public.medicine_dispensations
  FOR EACH ROW
  EXECUTE FUNCTION public.record_medicine_dispense_movement();

  INSERT INTO public.inventory_movements (
    medicine_id, movement_type, quantity_change, dispensation_id, patient_id,
    assessment_id, recorded_by, reason, created_at
  )
  SELECT
    dispensation.medicine_id,
    'dispensed',
    -dispensation.quantity,
    dispensation.id,
    dispensation.patient_id,
    dispensation.assessment_id,
    dispensation.dispensed_by,
    'Existing clinic assessment dispensation',
    dispensation.dispensed_at
  FROM public.medicine_dispensations AS dispensation
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.inventory_movements AS movement
    WHERE movement.dispensation_id = dispensation.id
  );

