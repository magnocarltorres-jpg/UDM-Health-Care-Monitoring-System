CREATE OR REPLACE FUNCTION public.get_clinic_report(
  p_from date,
  p_to date
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
  v_result jsonb;
BEGIN
  IF p_from IS NULL OR p_to IS NULL OR p_to < p_from OR p_to - p_from > 365 THEN
    RAISE EXCEPTION 'INVALID_REPORT_DATE_RANGE';
  END IF;

  SELECT jsonb_build_object(
    'newPatients', (
      SELECT count(*)
      FROM public.patients
      WHERE (created_at AT TIME ZONE 'Asia/Manila')::date BETWEEN p_from AND p_to
    ),
    'visits', (
      SELECT count(*)
      FROM public.clinic_assessments
      WHERE (created_at AT TIME ZONE 'Asia/Manila')::date BETWEEN p_from AND p_to
    ),
    'dispensedUnits', (
      SELECT COALESCE(sum(-quantity_change), 0)
      FROM public.inventory_movements
      WHERE movement_type = 'dispensed'
        AND (created_at AT TIME ZONE 'Asia/Manila')::date BETWEEN p_from AND p_to
    ),
    'visitsByDay', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('date', days.day, 'count', COALESCE(visits.count, 0)) ORDER BY days.day)
      FROM generate_series(p_from, p_to, interval '1 day') AS days(day)
      LEFT JOIN (
        SELECT (created_at AT TIME ZONE 'Asia/Manila')::date AS day, count(*) AS count
        FROM public.clinic_assessments
        WHERE (created_at AT TIME ZONE 'Asia/Manila')::date BETWEEN p_from AND p_to
        GROUP BY 1
      ) AS visits ON visits.day = days.day::date
    ), '[]'::jsonb),
    'topMedicines', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'name', medicine_name,
        'units', units
      ) ORDER BY units DESC)
      FROM (
        SELECT COALESCE(m.brand_name, m.generic_name) AS medicine_name,
               sum(-movement.quantity_change)::integer AS units
        FROM public.inventory_movements AS movement
        JOIN public.medicines AS m ON m.id = movement.medicine_id
        WHERE movement.movement_type = 'dispensed'
          AND (movement.created_at AT TIME ZONE 'Asia/Manila')::date BETWEEN p_from AND p_to
        GROUP BY COALESCE(m.brand_name, m.generic_name)
        ORDER BY units DESC
        LIMIT 5
      ) AS top_medicines
    ), '[]'::jsonb),
    'inventoryAlerts', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', id,
        'name', COALESCE(brand_name, generic_name),
        'batchNumber', batch_number,
        'stockQuantity', stock_quantity,
        'expirationDate', expiration_date,
        'status', CASE
          WHEN expiration_date < CURRENT_DATE THEN 'expired'
          WHEN COALESCE(stock_quantity, 0) <= 10 THEN 'low_stock'
          WHEN expiration_date <= CURRENT_DATE + 30 THEN 'expiring_soon'
        END
      ) ORDER BY expiration_date ASC NULLS LAST)
      FROM public.medicines
      WHERE expiration_date < CURRENT_DATE
         OR COALESCE(stock_quantity, 0) <= 10
         OR expiration_date <= CURRENT_DATE + 30
    ), '[]'::jsonb)
  )
  INTO v_result;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_clinic_report(date, date)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_clinic_report(date, date)
  TO service_role;

