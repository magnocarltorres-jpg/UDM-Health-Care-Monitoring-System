DROP FUNCTION IF EXISTS public.create_medicine_batch(
  text, text, text, text, date, integer, text, integer
);
CREATE FUNCTION public.create_medicine_batch(
  p_item_code text,
  p_generic_name text,
  p_category text,
  p_strength text,
  p_expiration_date date,
  p_stock_quantity integer,
  p_batch_number text,
  p_recorded_by integer
)
RETURNS public.medicines
LANGUAGE plpgsql
AS $$
DECLARE
  v_medicine public.medicines%ROWTYPE;
BEGIN
  IF p_stock_quantity IS NULL OR p_stock_quantity < 0 THEN
    RAISE EXCEPTION 'INVALID_INITIAL_STOCK';
  END IF;

  IF p_batch_number IS NULL OR btrim(p_batch_number) = '' THEN
    RAISE EXCEPTION 'BATCH_NUMBER_REQUIRED';
  END IF;

  INSERT INTO public.medicines (
    item_code, generic_name, category, strength, expiration_date,
    stock_quantity, batch_number
  )
  VALUES (
    p_item_code, p_generic_name, p_category, p_strength, p_expiration_date,
    p_stock_quantity, btrim(p_batch_number)
  )
  RETURNING * INTO v_medicine;

  IF p_stock_quantity > 0 THEN
    INSERT INTO public.inventory_movements (
      medicine_id, movement_type, quantity_change, recorded_by, reason
    )
    VALUES (
      v_medicine.id, 'received', p_stock_quantity, p_recorded_by,
      'Initial batch received'
    );
  END IF;

  RETURN v_medicine;
END;
$$;

DROP FUNCTION IF EXISTS public.restock_medicine(integer, integer);
CREATE FUNCTION public.restock_medicine(
  p_medicine_id integer,
  p_quantity integer,
  p_recorded_by integer
)
RETURNS public.medicines
LANGUAGE plpgsql
AS $$
DECLARE
  v_medicine public.medicines%ROWTYPE;
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE EXCEPTION 'INVALID_RESTOCK_QUANTITY';
  END IF;

  UPDATE public.medicines
  SET stock_quantity = COALESCE(stock_quantity, 0) + p_quantity
  WHERE id = p_medicine_id
  RETURNING * INTO v_medicine;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'MEDICINE_NOT_FOUND';
  END IF;

  INSERT INTO public.inventory_movements (
    medicine_id, movement_type, quantity_change, recorded_by, reason
  )
  VALUES (
    p_medicine_id, 'received', p_quantity, p_recorded_by, 'Stock restocked'
  );

  RETURN v_medicine;
END;
$$;

