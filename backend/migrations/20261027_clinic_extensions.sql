DROP FUNCTION IF EXISTS public.restock_medicine(bigint, integer);

CREATE OR REPLACE FUNCTION public.restock_medicine(
  p_medicine_id integer,
  p_quantity integer
)
RETURNS public.medicines
LANGUAGE plpgsql
AS $$
DECLARE
  v_medicine public.medicines%ROWTYPE;
BEGIN
  IF p_quantity IS NULL OR p_quantity <= 0 THEN
    RAISE EXCEPTION 'INVALID_RESTOCK_QUANTITY';
  END IF;

  UPDATE public.medicines
  SET stock_quantity = COALESCE(stock_quantity, 0) + p_quantity
  WHERE id = p_medicine_id
  RETURNING * INTO v_medicine;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'MEDICINE_NOT_FOUND';
  END IF;

  RETURN v_medicine;
END;
$$;

DROP FUNCTION IF EXISTS public.create_clinic_assessment(
  bigint, numeric, numeric, text, numeric, numeric, numeric, numeric,
  text, text, text, integer, bigint, integer
);

CREATE OR REPLACE FUNCTION public.create_clinic_assessment(
  p_patient_id bigint,
  p_height numeric,
  p_weight numeric,
  p_blood_pressure text,
  p_temperature numeric,
  p_heart_rate numeric,
  p_spo2 numeric,
  p_bmi numeric,
  p_bmi_status text,
  p_reason text,
  p_notes text,
  p_recorded_by integer,
  p_medicine_id integer DEFAULT NULL,
  p_dispense_quantity integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient public.patients%ROWTYPE;
  v_assessment public.clinic_assessments%ROWTYPE;
BEGIN
  SELECT * INTO v_patient
  FROM public.patients
  WHERE id = p_patient_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PATIENT_NOT_FOUND';
  END IF;

  IF (p_medicine_id IS NULL) <> (p_dispense_quantity IS NULL) THEN
    RAISE EXCEPTION 'MEDICINE_AND_QUANTITY_REQUIRED';
  END IF;

  IF p_dispense_quantity IS NOT NULL AND p_dispense_quantity <= 0 THEN
    RAISE EXCEPTION 'INVALID_DISPENSE_QUANTITY';
  END IF;

  INSERT INTO public.clinic_assessments (
    patient_id, student_number, patient_identifier, height, weight,
    blood_pressure, temperature, heart_rate, spo2, bmi, bmi_status,
    reason, notes, recorded_by
  )
  VALUES (
    v_patient.id, v_patient.student_number, v_patient.patient_id,
    p_height, p_weight, p_blood_pressure, p_temperature, p_heart_rate,
    p_spo2, p_bmi, p_bmi_status, p_reason, p_notes, p_recorded_by
  )
  RETURNING * INTO v_assessment;

  IF p_medicine_id IS NOT NULL THEN
    UPDATE public.medicines
    SET stock_quantity = COALESCE(stock_quantity, 0) - p_dispense_quantity
    WHERE id = p_medicine_id
      AND COALESCE(stock_quantity, 0) >= p_dispense_quantity
      AND expiration_date IS NOT NULL
      AND expiration_date >= CURRENT_DATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'MEDICINE_UNAVAILABLE';
    END IF;

    INSERT INTO public.medicine_dispensations (
      assessment_id, patient_id, medicine_id, quantity, dispensed_by
    )
    VALUES (
      v_assessment.id, v_patient.id, p_medicine_id,
      p_dispense_quantity, p_recorded_by
    );
  END IF;

  RETURN to_jsonb(v_assessment);
END;
$$;

