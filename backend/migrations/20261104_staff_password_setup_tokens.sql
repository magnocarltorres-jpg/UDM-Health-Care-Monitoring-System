CREATE TABLE IF NOT EXISTS public.staff_password_setup_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_account_id integer NOT NULL REFERENCES public.staff_accounts(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS staff_password_setup_tokens_account_id_idx
  ON public.staff_password_setup_tokens (staff_account_id);

CREATE UNIQUE INDEX IF NOT EXISTS staff_password_setup_tokens_one_unused_idx
  ON public.staff_password_setup_tokens (staff_account_id)
  WHERE used_at IS NULL;

ALTER TABLE public.staff_password_setup_tokens ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.staff_password_setup_tokens
FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.staff_password_setup_tokens TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.staff_password_setup_tokens_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.redeem_staff_password_setup_token(
  p_token_hash text,
  p_password_hash text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_staff_account_id integer;
BEGIN
  UPDATE public.staff_password_setup_tokens
  SET used_at = now()
  WHERE token_hash = p_token_hash
    AND used_at IS NULL
    AND expires_at > now()
  RETURNING staff_account_id INTO v_staff_account_id;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE public.staff_accounts
  SET password = p_password_hash,
      must_change_password = false
  WHERE id = v_staff_account_id
    AND lower(status) = 'active';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Staff account is not active or no longer exists.';
  END IF;

  RETURN true;
END;
$$;

REVOKE ALL PRIVILEGES ON FUNCTION public.redeem_staff_password_setup_token(text, text)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.redeem_staff_password_setup_token(text, text)
TO service_role;

NOTIFY pgrst, 'reload schema';
